-- SERPAPI Webcrawler tables for manager_main.
-- Apply this SQL in the manager_main database before using the tool.

CREATE TABLE IF NOT EXISTS `serpapi_searches` (
  `id` int NOT NULL AUTO_INCREMENT,
  `user_id` int DEFAULT NULL,
  `search_type` varchar(20) NOT NULL DEFAULT 'web',
  `engine` varchar(50) NOT NULL DEFAULT 'google',
  `query` varchar(300) NOT NULL,
  `location` varchar(255) DEFAULT NULL,
  `country_code` varchar(2) DEFAULT NULL,
  `language_code` varchar(10) NOT NULL DEFAULT 'pt',
  `device` varchar(20) NOT NULL DEFAULT 'desktop',
  `safe_search` varchar(20) NOT NULL DEFAULT 'active',
  `result_count` int NOT NULL DEFAULT '10',
  `start_offset` int NOT NULL DEFAULT '0',
  `request_params_json` json DEFAULT NULL,
  `response_metadata_json` json DEFAULT NULL,
  `raw_response_json` longtext,
  `query_count` int NOT NULL DEFAULT '0',
  `result_total` int NOT NULL DEFAULT '0',
  `processed_total` int NOT NULL DEFAULT '0',
  `failed_total` int NOT NULL DEFAULT '0',
  `status` varchar(20) NOT NULL DEFAULT 'running',
  `message` varchar(500) DEFAULT NULL,
  `usage_period` char(7) DEFAULT NULL,
  `usage_limit` int NOT NULL DEFAULT '250',
  `usage_used` int NOT NULL DEFAULT '0',
  `usage_remaining` int NOT NULL DEFAULT '250',
  `response_time_ms` int NOT NULL DEFAULT '0',
  `http_status` int NOT NULL DEFAULT '0',
  `started_at` datetime DEFAULT NULL,
  `finished_at` datetime DEFAULT NULL,
  `created` datetime DEFAULT NULL,
  `modified` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_serpapi_searches_user` (`user_id`),
  KEY `idx_serpapi_searches_status` (`status`),
  KEY `idx_serpapi_searches_type` (`search_type`),
  KEY `idx_serpapi_searches_period` (`usage_period`),
  KEY `idx_serpapi_searches_started` (`started_at`),
  CONSTRAINT `fk_serpapi_searches_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `serpapi_search_results` (
  `id` int NOT NULL AUTO_INCREMENT,
  `search_id` int NOT NULL,
  `user_id` int DEFAULT NULL,
  `search_type` varchar(20) NOT NULL DEFAULT 'web',
  `engine` varchar(50) NOT NULL DEFAULT 'google',
  `position` int NOT NULL DEFAULT '0',
  `title` varchar(500) DEFAULT NULL,
  `link` varchar(1000) DEFAULT NULL,
  `displayed_link` varchar(500) DEFAULT NULL,
  `source` varchar(255) DEFAULT NULL,
  `snippet` text,
  `thumbnail` varchar(1000) DEFAULT NULL,
  `result_date` varchar(100) DEFAULT NULL,
  `result_type` varchar(50) DEFAULT NULL,
  `result_hash` varchar(40) NOT NULL,
  `raw_result_json` json DEFAULT NULL,
  `checked_at` datetime DEFAULT NULL,
  `created` datetime DEFAULT NULL,
  `modified` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_serpapi_search_results_search_hash` (`search_id`,`result_hash`),
  KEY `idx_serpapi_search_results_search` (`search_id`),
  KEY `idx_serpapi_search_results_user` (`user_id`),
  KEY `idx_serpapi_search_results_type` (`search_type`),
  KEY `idx_serpapi_search_results_checked` (`checked_at`),
  KEY `idx_serpapi_search_results_link` (`link`(255)),
  CONSTRAINT `fk_serpapi_search_results_search` FOREIGN KEY (`search_id`) REFERENCES `serpapi_searches` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fk_serpapi_search_results_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `serpapi_usage_monthly` (
  `id` int NOT NULL AUTO_INCREMENT,
  `usage_period` char(7) NOT NULL,
  `quota_key` varchar(80) NOT NULL DEFAULT 'default',
  `limit_count` int NOT NULL DEFAULT '250',
  `used_count` int NOT NULL DEFAULT '0',
  `created` datetime DEFAULT NULL,
  `modified` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_serpapi_usage_monthly_period_key` (`usage_period`,`quota_key`),
  KEY `idx_serpapi_usage_monthly_period` (`usage_period`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
