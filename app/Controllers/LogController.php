<?php

namespace App\Controllers;

use App\Core\Controller;
use App\Models\Log;
use App\Models\User;

class LogController extends Controller
	{
	private const DELETE_PASSWORD_EMAIL = 'admin@admin.com';

	/**
	 * Route aliases accepted by this controller.
	 *
	 * @var array<string, string>
	 */
	protected $routeAliases = [
		'user-timeline' => 'userTimeline',
		'user_timeline' => 'userTimeline',
	];

	/**
	 * Displays the audit log listing with filters and pagination.
	 *
	 * @return void
	 */
	public function index(): void
		{
		$this->requirePermission('log.index');

		// Filters are kept explicit so pagination can reproduce the exact search.
		$filters = [
			'id' => isset($_GET['id']) ? trim((string) $_GET['id']) : '',
			'tenant' => isset($_GET['tenant']) ? trim((string) $_GET['tenant']) : '',
			'module' => isset($_GET['module']) ? trim((string) $_GET['module']) : '',
			'action' => isset($_GET['action']) ? trim((string) $_GET['action']) : '',
			'entity_name' => isset($_GET['entity_name']) ? trim((string) $_GET['entity_name']) : '',
			'entity_id' => isset($_GET['entity_id']) ? trim((string) $_GET['entity_id']) : '',
			'performed_by' => isset($_GET['performed_by']) ? trim((string) $_GET['performed_by']) : '',
			'route' => isset($_GET['route']) ? trim((string) $_GET['route']) : '',
			'date_from' => isset($_GET['date_from']) ? trim((string) $_GET['date_from']) : '',
			'date_to' => isset($_GET['date_to']) ? trim((string) $_GET['date_to']) : '',
		];

		// Pagination values are normalized before querying the model.
		$page = isset($_GET['page']) ? (int) $_GET['page'] : 1;
		if ($page < 1)
			{
			$page = 1;
			}

		$perPage = 20;
		$offset = ($page - 1) * $perPage;

		$logModel = new Log();
		$sort = sortRequest(Log::sortableColumns(), 'occurred_at', 'desc');
		$logs = $logModel->search($filters, $perPage, $offset, $sort);
		$total = $logModel->count($filters);
		$totalPages = (int) ceil($total / $perPage);

		if ($totalPages < 1)
			{
			$totalPages = 1;
			}

		$modules = $logModel->getModules();
		$actions = Log::actionLabels();

		if ($this->wantsJson())
			{
			$this->json([
				'filters' => $filters,
				'page' => $page,
				'perPage' => $perPage,
				'total' => $total,
				'totalPages' => $totalPages,
				'sort' => $sort,
				'modules' => $modules,
				'actions' => $actions,
				'data' => $logs,
			]);
			}

		$this->view('logs/index', [
			'title' => 'Logs do sistema',
			'logs' => $logs,
			'filters' => $filters,
			'page' => $page,
			'totalPages' => $totalPages,
			'total' => $total,
			'sort' => $sort,
			'modules' => $modules,
			'actions' => $actions,
		]);
		}

	/**
	 * Displays a readable detail page for a single audit event.
	 *
	 * @param int|string $id Log ID.
	 * @return void
	 */
	public function informations($id): void
		{
		$this->requirePermission('log.informations');

		$logModel = new Log();
		$log = $logModel->find($id);

		if ($log === null)
			{
			$this->redirect('log');
			}

		$userTimeline = [];
		if (!empty($log['performed_by_user_id']))
			{
			$userTimeline = $logModel->recentUserTimeline((int) $log['performed_by_user_id'], 12);
			}

		$this->view('logs/informations', [
			'title' => 'Detalhes do log',
			'log' => $log,
			'userTimeline' => $userTimeline,
			'actions' => Log::actionLabels(),
		]);
		}

	/**
	 * Displays a timeline with all logs generated by a single user.
	 *
	 * @param int|string $userId User ID.
	 * @return void
	 */
	public function userTimeline($userId): void
		{
		$this->requirePermission('log.userTimeline');

		$selectedUserId = (int) $userId;
		if ($selectedUserId <= 0)
			{
			$this->redirect('log');
			}

		$filters = [
			'action' => isset($_GET['action']) ? trim((string) $_GET['action']) : '',
			'module' => isset($_GET['module']) ? trim((string) $_GET['module']) : '',
			'tenant' => isset($_GET['tenant']) ? trim((string) $_GET['tenant']) : '',
			'date_from' => isset($_GET['date_from']) ? trim((string) $_GET['date_from']) : '',
			'date_to' => isset($_GET['date_to']) ? trim((string) $_GET['date_to']) : '',
		];

		$page = isset($_GET['page']) ? (int) $_GET['page'] : 1;
		if ($page < 1)
			{
			$page = 1;
			}

		$perPage = 25;
		$offset = ($page - 1) * $perPage;

		$logModel = new Log();
		$user = $logModel->findLoggedUser($selectedUserId);

		if ($user === null)
			{
			$this->redirect('log');
			}

		$logs = $logModel->searchUserTimeline($selectedUserId, $filters, $perPage, $offset);
		$total = $logModel->countUserTimeline($selectedUserId, $filters);
		$totalPages = (int) ceil($total / $perPage);
		if ($totalPages < 1)
			{
			$totalPages = 1;
			}

		$this->view('logs/user_timeline', [
			'title' => 'Linha do tempo do usuário',
			'user' => $user,
			'userId' => $selectedUserId,
			'logs' => $logs,
			'filters' => $filters,
			'actions' => Log::actionLabels(),
			'modules' => $logModel->getModules(),
			'page' => $page,
			'totalPages' => $totalPages,
			'total' => $total,
		]);
		}

	/**
	 * Deletes a log entry after validating the administrative password.
	 *
	 * @param int|string $id Log ID.
	 * @return void
	 */
	public function delete($id): void
		{
		$this->requirePermission('log.informations');

		if ($_SERVER['REQUEST_METHOD'] !== 'POST')
			{
			if ($this->wantsJson())
				{
				$this->json([
					'error' => 'method_not_allowed',
					'message' => 'Método não permitido.',
				], 405);
				}

			$this->redirect('log');
			}

		$logId = (int) $id;
		if ($logId <= 0)
			{
			$this->json([
				'error' => 'invalid_log',
				'message' => 'Log inválido.',
			], 422);
			}

		$password = isset($_POST['password']) ? (string) $_POST['password'] : '';
		if (!$this->isDeletePasswordValid($password))
			{
			$this->json([
				'error' => 'invalid_password',
				'message' => 'Senha inválida para remover o log.',
			], 422);
			}

		$logModel = new Log();
		$log = $logModel->find($logId);

		if ($log === null)
			{
			$this->json([
				'error' => 'not_found',
				'message' => 'Log não encontrado.',
			], 404);
			}

		$deleted = $logModel->delete($logId);
		if (!$deleted)
			{
			$this->json([
				'error' => 'delete_failed',
				'message' => 'Não foi possível remover o log.',
			], 500);
			}

		$this->json([
			'success' => true,
			'deletedId' => $logId,
			'message' => 'Log removido com sucesso.',
			'redirect' => url('log'),
		]);
		}

	/**
	 * Validates the confirmation password used to delete audit logs.
	 *
	 * @param string $password Raw password entered in the modal.
	 * @return bool
	 */
	private function isDeletePasswordValid(string $password): bool
		{
		$password = trim($password);
		if ($password === '')
			{
			return false;
			}

		$userModel = new User();
		return $userModel->authenticate(self::DELETE_PASSWORD_EMAIL, $password) !== false;
		}
	}
?>
