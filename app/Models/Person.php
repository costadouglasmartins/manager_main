<?php

namespace App\Models;

use App\Core\Model;
use App\Services\TenantProvisioner;
use PDO;

/**
 * Manages people and their directly related records.
 *
 * This model coordinates the `people`, `users`, `tenant_users`,
 * `phone_numbers`, `addresses` and `emails` tables. Create, update and delete
 * flows use database transactions so the person aggregate is persisted as a
 * single unit.
 */
class Person extends Model
	{
	/**
	 * Returns sortable columns for list queries.
	 *
	 * @return array<string, string>
	 */
	public static function sortableColumns(): array
		{
		return [
			'id'        => 'id',
			'name'      => '`name`',
			'document'  => '`document`',
			'birthdate' => '`birthdate`',
			'type'      => '`type`',
		];
		}

	/**
	 * Returns all registered people.
	 *
	 * Records are ordered from newest to oldest.
	 *
	 * @return array<int, array<string, mixed>>
	 */
	public function getAll()
		{
		$stmt = $this->db->query("SELECT * FROM people ORDER BY id DESC");
		return $stmt->fetchAll(PDO::FETCH_ASSOC);
		}

	/**
	 * Regroups form arrays generated by `name="arr[][key]"` fields.
	 *
	 * When PHP receives each key in a different index, this method rebuilds the
	 * records by position. If the data is already grouped, it is returned unchanged.
	 *
	 * @param array<int, mixed> $items Items received from the form.
	 * @return array<int, array<string, mixed>>
	 */
	private function regroupFormArray(array $items): array
		{
		// Detect: if any entry has more than one key, assume already grouped
		foreach ($items as $entry)
			{
			if (is_array($entry) && count($entry) > 1)
				{
				return $items;
				}
			}

		// Collect values per key, preserving order
		$byKey = [];
		foreach ($items as $entry)
			{
			if (!is_array($entry))
				{
				continue;
				}
			foreach ($entry as $key => $value)
				{
				$byKey[$key][] = $value;
				}
			}

		if (empty($byKey))
			{
			return [];
			}

		// Zip: the first key determines how many records there are
		$keys  = array_keys($byKey);
		$count = count(reset($byKey));
		$result = [];

		for ($i = 0; $i < $count; $i++)
			{
			$row = [];
			foreach ($keys as $key)
				{
				$row[$key] = $byKey[$key][$i] ?? null;
				}
			$result[] = $row;
			}

		return $result;
		}

	/**
	 * Creates a person and related records within a transaction.
	 *
	 * Saves the main record, user, phones, addresses, emails and, when provided,
	 * creates or links the corresponding tenant.
	 * Expected top-level sections are `person`, `user`, `tenant`, `phones`,
	 * `addresses` and `emails`.
	 *
	 * @param array<string, mixed> $data Form data grouped by `person`, `user`, `tenant`, `phones`, `addresses` and `emails`.
	 * @return array{person_id: int|string, user_id: int|string, tenant_id: int|null}
	 * @throws \Exception If any write fails; the transaction is rolled back.
	 */
	public function create($data)
		{

		try
			{
			$this->db->beginTransaction();

			// Insert the base person record and normalize the date/document fields.
			$sqlPerson = "INSERT INTO people
                        (`name`, `fantasy`, `type`, `document`, `active`, `birthdate`, `created`, `modified`)
                      VALUES
                        (:name, :fantasy, :type, :document, :active, :birthdate, :created, :modified)";

			$birthdate = (!empty($data['person']['birthdate'])) ? dateBrToUs($data['person']['birthdate']) : null;

			$stmtPerson = $this->db->prepare($sqlPerson);
			$stmtPerson->execute([
				'name'      => $data['person']['name'],
				'fantasy'   => $data['person']['fantasy'] ?? '',
				'type'      => $data['person']['type'],
				'document'  => onlyDigits($data['person']['document']),
				'active'    => intval($data['person']['active'] ?? 1),
				'birthdate' => $birthdate,
				'created'   => date('Y-m-d H:i:s'),
				'modified'  => date('Y-m-d H:i:s'),
			]);
			$personId = $this->db->lastInsertId();

			// Create the login user linked to the newly created person.
			$sqlUser = "INSERT INTO users
                      (`person_id`, `username`, `password`, `type`, `active`, `created`, `modified`)
                    VALUES
                      (:person_id, :username, :password, :type, :active, :created, :modified)";
			$stmtUser = $this->db->prepare($sqlUser);
			$stmtUser->execute([
				'person_id' => $personId,
				'username'  => $data['user']['username'],
				'password'  => password_hash($data['user']['password'], PASSWORD_DEFAULT),
				'type'      => $data['user']['type'],
				'active'    => intval($data['user']['active'] ?? 1),
				'created'   => date('Y-m-d H:i:s'),
				'modified'  => date('Y-m-d H:i:s'),
			]);
			$userId = $this->db->lastInsertId();

			// Resolve the tenant relationship requested by the form.
			$tenantId = null;
			$tenantMode = $data['tenant']['mode'] ?? 'none';

			if ($tenantMode === 'new')
				{
					$tenantModel = new Tenant();
					$databaseNumber = $tenantModel->nextDatabaseNumber();
					$tenantStatus = 'active';

					// Create the tenant as pending until its database is provisioned.
					$tenantId = $tenantModel->create([
						'database_number' => $databaseNumber,
						'status'          => 'pending',
						'observations'    => $data['tenant']['observations'] ?? null,
					]);

					$provisioner = new TenantProvisioner();
					$provisioned = $provisioner->provision($databaseNumber);

					// Activate the tenant only after successful provisioning.
					if ($provisioned)
						{
						$tenantModel->update($tenantId, [
							'status'       => $tenantStatus,
							'observations' => $data['tenant']['observations'] ?? null,
						]);
						}
					}
			elseif ($tenantMode === 'existing' && !empty($data['tenant']['existing_id']))
				{
				// Link the new user to an existing tenant selected in the form.
				$tenantId = (int) $data['tenant']['existing_id'];
				}

			// Store the primary tenant on the user and create the pivot link.
			if ($tenantId)
				{
				$stmtTenantLink = $this->db->prepare("UPDATE users SET tenant_id = :tenant_id, modified = :modified WHERE id = :id");
				$stmtTenantLink->execute([
					'tenant_id' => $tenantId,
					'modified'  => date('Y-m-d H:i:s'),
					'id'        => $userId,
				]);

				// The first user created through this flow owns the tenant.
				$tenantModel = new Tenant();
				$tenantModel->linkUser($tenantId, $userId, 'owner');
				}

			// Persist optional phone rows, skipping empty entries.
			if (!empty($data['phones']) && is_array($data['phones']))
				{
				$data['phones'] = $this->regroupFormArray($data['phones']);
				$sqlPhone = "INSERT INTO phone_numbers (`phone_number`, `observations`, `person_id`, `created`, `modified`)
                             VALUES (:phone_number, :observations, :person_id, :created, :modified)";
				$stmtPhone = $this->db->prepare($sqlPhone);
				foreach ($data['phones'] as $phone)
					{
					if (empty($phone['number']))
						{
						continue;
						}
					$stmtPhone->execute([
						'phone_number' => onlyDigits($phone['number']),
						'observations' => $phone['notes'] ?? null,
						'person_id'    => $personId,
						'created'      => date('Y-m-d H:i:s'),
						'modified'     => date('Y-m-d H:i:s'),
					]);
					}
				}

			// Persist optional address rows, requiring street and neighborhood.
			if (!empty($data['addresses']) && is_array($data['addresses']))
				{
				$data['addresses'] = $this->regroupFormArray($data['addresses']);
				$sqlAddress = "INSERT INTO addresses
								(`zip_code`, `street`, `number`, `observations`, `person_id`, `neighborhood_id`, `created`, `modified`)
							  VALUES
								(:zip_code, :street, :number, :observations, :person_id, :neighborhood_id, :created, :modified)";
				$stmtAddress = $this->db->prepare($sqlAddress);
				foreach ($data['addresses'] as $address)
					{
					if (empty($address['street']) || empty($address['neighborhood_id']))
						{
						continue;
						}
					$stmtAddress->execute([
						'zip_code'        => $address['zip_code'] ?? '',
						'street'          => $address['street'],
						'number'          => $address['number'] ?? '',
						'observations'    => $address['observations'] ?? null,
						'person_id'       => $personId,
						'neighborhood_id' => (int) $address['neighborhood_id'],
						'created'         => date('Y-m-d H:i:s'),
						'modified'        => date('Y-m-d H:i:s'),
					]);
					}
				}

			// Persist optional email rows, skipping entries without an address.
			if (!empty($data['emails']) && is_array($data['emails']))
				{
				$data['emails'] = $this->regroupFormArray($data['emails']);
				$sqlEmail = "INSERT INTO emails (`email`, `observations`, `is_login`, `person_id`, `created`, `modified`)
                             VALUES (:email, :observations, :is_login, :person_id, :created, :modified)";
				$stmtEmail = $this->db->prepare($sqlEmail);
				foreach ($data['emails'] as $email)
					{
					if (empty($email['address']))
						{
						continue;
						}
					$stmtEmail->execute([
						'email'        => $email['address'],
						'observations' => $email['description'] ?? null,
						'is_login'     => intval($email['is_login'] ?? 0),
						'person_id'    => $personId,
						'created'      => date('Y-m-d H:i:s'),
						'modified'     => date('Y-m-d H:i:s'),
					]);
					}
				}

			$this->db->commit();

			return [
				'person_id' => $personId,
				'user_id'   => $userId,
				'tenant_id' => $tenantId,
			];
			}
		catch (\Exception $e)
			{
			$this->db->rollBack();
			throw $e;
			}
		}

	/**
	 * Finds a person by ID.
	 *
	 * @param int|string $id Person ID.
	 * @return array<string, mixed>|false Person data or `false` when not found.
	 */
	public function find($id)
		{
		$stmt = $this->db->prepare("SELECT * FROM people WHERE id = :id");
		$stmt->execute(['id' => $id]);
		return $stmt->fetch(PDO::FETCH_ASSOC);
		}

	/**
	 * Updates a person and synchronizes related data.
	 *
	 * The operation updates the base record, user, tenant links, addresses,
	 * phones and emails within a transaction.
	 *
	 * @param int|string $id Person ID.
	 * @param array<string, mixed> $data Form data.
	 * @return void
	 * @throws \Exception If any write fails; the transaction is rolled back.
	 */
	public function update($id, $data)
		{
		$personId = (int) $id;
		$personData = (isset($data['person']) && is_array($data['person'])) ? $data['person'] : $data;

		try
			{
			$this->db->beginTransaction();

			// Update the base person fields before syncing child records.
			$this->updatePersonRecord($personId, $personData);

			// Create or update the associated user when user data was submitted.
			$userId = $this->upsertPersonUser($personId, $data['user'] ?? null);

			// Synchronize explicit tenant links from the edit form.
			if ($userId !== null && !empty($data['tenant_links']) && is_array($data['tenant_links']))
				{
				$this->saveTenantLinks($userId, $data['tenant_links']);
				}

			// Ensure the selected primary tenant also exists in tenant_users.
			if ($userId !== null && isset($data['user']['tenant_id']) && (int) $data['user']['tenant_id'] > 0)
				{
				$this->ensurePrimaryTenantLink($userId, (int) $data['user']['tenant_id']);
				}

			// Synchronize repeatable child sections only when they are present.
			if (!empty($data['addresses']) && is_array($data['addresses']))
				{
				$this->saveAddresses($personId, $data['addresses']);
				}

			if (!empty($data['phones']) && is_array($data['phones']))
				{
				$this->savePhones($personId, $data['phones']);
				}

			if (!empty($data['emails']) && is_array($data['emails']))
				{
				$this->saveEmails($personId, $data['emails']);
				}

			$this->db->commit();
			}
		catch (\Exception $e)
			{
			$this->db->rollBack();
			throw $e;
			}
		}

	/**
	 * Updates only the person's main record in the `people` table.
	 *
	 * @param int $personId Person ID.
	 * @param array<string, mixed> $data Basic person data.
	 * @return void
	 */
	private function updatePersonRecord(int $personId, array $data): void
		{
		$stmt = $this->db->prepare("
			UPDATE people
			SET
				`name`      = :name,
				`fantasy`   = :fantasy,
				`type`      = :type,
				`document`  = :document,
				`active`    = :active,
				`birthdate` = :birthdate,
				`modified`  = :modified
			WHERE id = :id
		");

		$stmt->execute([
			'name'      => trim((string) ($data['name'] ?? '')),
			'fantasy'   => $data['fantasy'] ?? '',
			'type'      => $data['type'] ?? 'individual',
			'document'  => onlyDigits($data['document'] ?? ''),
			'active'    => (int) ($data['active'] ?? 0),
			'birthdate' => (!empty($data['birthdate']) ? dateBrToUs($data['birthdate']) : null),
			'modified'  => date('Y-m-d H:i:s'),
			'id'        => $personId,
		]);
		}

	/**
	 * Creates or updates the user linked to a person.
	 *
	 * Validates username, password confirmation and user type before saving.
	 * When there is no valid user data to create, returns `null`.
	 * Existing users are updated in place; new users require a password.
	 *
	 * @param int $personId Person ID.
	 * @param mixed $data User data received from the form.
	 * @return int|null Created/updated user ID or `null` when nothing was saved.
	 * @throws \InvalidArgumentException When the password is invalid or required data is missing.
	 */
	private function upsertPersonUser(int $personId, $data): ?int
		{
		if (!is_array($data))
			{
			return null;
			}

		$userId = (int) ($data['id'] ?? 0);
		$username = trim((string) ($data['username'] ?? ''));
		$password = trim((string) ($data['password'] ?? ''));
		$passwordConfirm = trim((string) ($data['password_confirm'] ?? ''));

		if ($username === '' && $userId === 0)
			{
			return null;
			}

		if ($password !== '' && $password !== $passwordConfirm)
			{
			throw new \InvalidArgumentException('A confirmação de senha não confere.');
			}

		$type = $data['type'] ?? 'user';
		if (!in_array($type, ['root', 'admin', 'user'], true))
			{
			$type = 'user';
			}

		$active = (int) ($data['active'] ?? 1);
		$tenantId = (isset($data['tenant_id']) && $data['tenant_id'] !== '' && (int) $data['tenant_id'] > 0)
			? (int) $data['tenant_id']
			: null;

		// Update the existing user and change the password only when one was submitted.
		if ($userId > 0)
			{
			if ($username === '')
				{
				throw new \InvalidArgumentException('Informe o nome de usuário.');
				}

			$params = [
				'username'  => $username,
				'type'      => $type,
				'active'    => $active,
				'tenant_id' => $tenantId,
				'modified'  => date('Y-m-d H:i:s'),
				'id'        => $userId,
				'person_id' => $personId,
			];

			$passwordSql = '';
			if ($password !== '')
				{
				$passwordSql = ", `password` = :password";
				$params['password'] = password_hash($password, PASSWORD_DEFAULT);
				}

			$stmt = $this->db->prepare("UPDATE users
			                            SET `username`  = :username,
			                                `type`      = :type,
			                                `active`    = :active,
			                                `tenant_id` = :tenant_id,
			                                `modified`  = :modified
			                                {$passwordSql}
			                            WHERE id = :id
			                              AND person_id = :person_id");
			$stmt->execute($params);
			return $userId;
			}

		// New users must receive an initial password.
		if ($password === '')
			{
			throw new \InvalidArgumentException('Informe uma senha para criar o usuário.');
			}

		$stmt = $this->db->prepare("INSERT INTO users
		                            (`person_id`, `tenant_id`, `username`, `password`, `type`, `active`, `created`, `modified`)
		                            VALUES
		                            (:person_id, :tenant_id, :username, :password, :type, :active, :created, :modified)");
		$stmt->execute([
			'person_id' => $personId,
			'tenant_id' => $tenantId,
			'username'  => $username,
			'password'  => password_hash($password, PASSWORD_DEFAULT),
			'type'      => $type,
			'active'    => $active,
			'created'   => date('Y-m-d H:i:s'),
			'modified'  => date('Y-m-d H:i:s'),
		]);

		return (int) $this->db->lastInsertId();
		}

	/**
	 * Ensures the user is linked to the provided primary tenant.
	 *
	 * @param int $userId User ID.
	 * @param int $tenantId Tenant ID.
	 * @return void
	 */
	private function ensurePrimaryTenantLink(int $userId, int $tenantId): void
		{
		$tenantModel = new Tenant();
		if (!$tenantModel->hasUser($tenantId, $userId))
			{
				$tenantModel->linkUser($tenantId, $userId, 'user');
			}
		}

	/**
	 * Synchronizes a user's tenant links.
	 *
	 * Regroups form data, removes links marked for deletion, updates basic tenant
	 * data when sent and creates/updates the role in `tenant_users`.
	 * Invalid tenant IDs are ignored so blank repeatable rows do not fail the
	 * whole update.
	 *
	 * @param int $userId User ID.
	 * @param array<int, mixed> $links Links received from the form.
	 * @return void
	 */
	private function saveTenantLinks(int $userId, array $links): void
		{
		$links = $this->regroupFormArray($links);
		$tenantModel = new Tenant();

		foreach ($links as $link)
			{
			if (!is_array($link))
				{
				continue;
				}

			$tenantId = (int) ($link['tenant_id'] ?? 0);
			if ($tenantId <= 0)
				{
				continue;
				}

			// Remove the pivot record when the form marks the link for deletion.
			if ($this->isDeleteRequested($link))
				{
				$tenantModel->unlinkUser($tenantId, $userId);
				continue;
				}

			// Update tenant status/notes when those fields are present.
			if (isset($link['status']) || array_key_exists('observations', $link))
				{
				$tenantModel->update($tenantId, [
					'status'       => $link['status'] ?? 'pending',
					'observations' => $link['observations'] ?? null,
				]);
				}

			// Keep roles inside the values supported by tenant_users.
			$role = $link['role'] ?? 'user';
			if (!in_array($role, ['owner', 'admin', 'user'], true))
				{
				$role = 'user';
				}

			// Upsert the pivot relationship with its role.
			if ($tenantModel->hasUser($tenantId, $userId))
				{
				$tenantModel->updateUserLink($tenantId, $userId, $role);
				}
			else
				{
				$tenantModel->linkUser($tenantId, $userId, $role);
				}
			}
		}

	/**
	 * Creates, updates or removes a person's addresses.
	 *
	 * Rows without street or neighborhood are ignored; rows marked with
	 * `_delete = 1` remove the existing address.
	 * Existing rows are matched by `id`; rows without an `id` are inserted.
	 *
	 * @param int $personId Person ID.
	 * @param array<int, mixed> $addresses Addresses received from the form.
	 * @return void
	 */
	private function saveAddresses(int $personId, array $addresses): void
		{
		$addresses = $this->regroupFormArray($addresses);

		foreach ($addresses as $address)
			{
			if (!is_array($address))
				{
				continue;
				}

			$addressId = (int) ($address['id'] ?? 0);

			// Delete only existing addresses that belong to this person.
			if ($this->isDeleteRequested($address))
				{
				if ($addressId > 0)
					{
					$stmt = $this->db->prepare("DELETE FROM addresses WHERE id = :id AND person_id = :person_id");
					$stmt->execute(['id' => $addressId, 'person_id' => $personId]);
					}
				continue;
				}

			$street = trim((string) ($address['street'] ?? ''));
			$neighborhoodId = (int) ($address['neighborhood_id'] ?? 0);
			if ($street === '' || $neighborhoodId <= 0)
				{
				continue;
				}

			// Shared payload used by both update and insert operations.
			$params = [
				'zip_code'        => $address['zip_code'] ?? '',
				'street'          => $street,
				'number'          => $address['number'] ?? '',
				'observations'    => $address['observations'] ?? null,
				'person_id'       => $personId,
				'neighborhood_id' => $neighborhoodId,
				'modified'        => date('Y-m-d H:i:s'),
			];

			// Update existing address rows by ID and person ownership.
			if ($addressId > 0)
				{
				$params['id'] = $addressId;
				$stmt = $this->db->prepare("UPDATE addresses
				                            SET `zip_code`        = :zip_code,
				                                `street`          = :street,
				                                `number`          = :number,
				                                `observations`    = :observations,
				                                `neighborhood_id` = :neighborhood_id,
				                                `modified`        = :modified
				                            WHERE id = :id
				                              AND person_id = :person_id");
				$stmt->execute($params);
				continue;
				}

			// Insert a new address row when no existing ID was submitted.
			$params['created'] = date('Y-m-d H:i:s');
			$stmt = $this->db->prepare("INSERT INTO addresses
			                            (`zip_code`, `street`, `number`, `observations`, `person_id`, `neighborhood_id`, `created`, `modified`)
			                            VALUES
			                            (:zip_code, :street, :number, :observations, :person_id, :neighborhood_id, :created, :modified)");
			$stmt->execute($params);
			}
		}

	/**
	 * Creates, updates or removes a person's phone numbers.
	 *
	 * The number is normalized to digits only; rows without a number are ignored.
	 * Existing rows are matched by `id`; rows without an `id` are inserted.
	 *
	 * @param int $personId Person ID.
	 * @param array<int, mixed> $phones Phones received from the form.
	 * @return void
	 */
	private function savePhones(int $personId, array $phones): void
		{
		$phones = $this->regroupFormArray($phones);

		foreach ($phones as $phone)
			{
			if (!is_array($phone))
				{
				continue;
				}

			$phoneId = (int) ($phone['id'] ?? 0);

			// Delete only existing phone numbers that belong to this person.
			if ($this->isDeleteRequested($phone))
				{
				if ($phoneId > 0)
					{
					$stmt = $this->db->prepare("DELETE FROM phone_numbers WHERE id = :id AND person_id = :person_id");
					$stmt->execute(['id' => $phoneId, 'person_id' => $personId]);
					}
				continue;
				}

			$number = onlyDigits($phone['number'] ?? ($phone['phone_number'] ?? ''));
			if ($number === '')
				{
				continue;
				}

			// Shared payload used by both update and insert operations.
			$params = [
				'phone_number' => $number,
				'observations' => $phone['notes'] ?? ($phone['observations'] ?? null),
				'person_id'    => $personId,
				'modified'     => date('Y-m-d H:i:s'),
			];

			// Update existing phone rows by ID and person ownership.
			if ($phoneId > 0)
				{
				$params['id'] = $phoneId;
				$stmt = $this->db->prepare("UPDATE phone_numbers
				                            SET `phone_number` = :phone_number,
				                                `observations` = :observations,
				                                `modified`     = :modified
				                            WHERE id = :id
				                              AND person_id = :person_id");
				$stmt->execute($params);
				continue;
				}

			// Insert a new phone row when no existing ID was submitted.
			$params['created'] = date('Y-m-d H:i:s');
			$stmt = $this->db->prepare("INSERT INTO phone_numbers
			                            (`phone_number`, `observations`, `person_id`, `created`, `modified`)
			                            VALUES
			                            (:phone_number, :observations, :person_id, :created, :modified)");
			$stmt->execute($params);
			}
		}

	/**
	 * Creates, updates or removes a person's emails.
	 *
	 * Rows without an email address are ignored; rows marked with `_delete = 1`
	 * remove the existing email.
	 * Existing rows are matched by `id`; rows without an `id` are inserted.
	 *
	 * @param int $personId Person ID.
	 * @param array<int, mixed> $emails Emails received from the form.
	 * @return void
	 */
	private function saveEmails(int $personId, array $emails): void
		{
		$emails = $this->regroupFormArray($emails);

		foreach ($emails as $email)
			{
			if (!is_array($email))
				{
				continue;
				}

			$emailId = (int) ($email['id'] ?? 0);

			// Delete only existing email rows that belong to this person.
			if ($this->isDeleteRequested($email))
				{
				if ($emailId > 0)
					{
					$stmt = $this->db->prepare("DELETE FROM emails WHERE id = :id AND person_id = :person_id");
					$stmt->execute(['id' => $emailId, 'person_id' => $personId]);
					}
				continue;
				}

			$emailAddress = trim((string) ($email['address'] ?? ($email['email'] ?? '')));
			if ($emailAddress === '')
				{
				continue;
				}

			// Shared payload used by both update and insert operations.
			$params = [
				'email'        => $emailAddress,
				'observations' => $email['description'] ?? ($email['observations'] ?? null),
				'is_login'     => (int) ($email['is_login'] ?? 0),
				'person_id'    => $personId,
				'modified'     => date('Y-m-d H:i:s'),
			];

			// Update existing email rows by ID and person ownership.
			if ($emailId > 0)
				{
				$params['id'] = $emailId;
				$stmt = $this->db->prepare("UPDATE emails
				                            SET `email`        = :email,
				                                `observations` = :observations,
				                                `is_login`     = :is_login,
				                                `modified`     = :modified
				                            WHERE id = :id
				                              AND person_id = :person_id");
				$stmt->execute($params);
				continue;
				}

			// Insert a new email row when no existing ID was submitted.
			$params['created'] = date('Y-m-d H:i:s');
			$stmt = $this->db->prepare("INSERT INTO emails
			                            (`email`, `observations`, `is_login`, `person_id`, `created`, `modified`)
			                            VALUES
			                            (:email, :observations, :is_login, :person_id, :created, :modified)");
			$stmt->execute($params);
			}
		}

	/**
	 * Indicates whether a form row was marked for deletion.
	 *
	 * @param array<string, mixed> $row Row received from the form.
	 * @return bool
	 */
	private function isDeleteRequested(array $row): bool
		{
		return isset($row['_delete']) && (string) $row['_delete'] === '1';
		}

	/**
	 * Searches people using optional filters and pagination.
	 *
	 * Accepted filters: `id`, `name`, `type`, `document`, `active` and `birthdate`.
	 *
	 * @param array<string, mixed> $filters Search filters.
	 * @param int $limit Maximum number of returned records.
	 * @param int $offset Pagination start position.
	 * @return array<int, array<string, mixed>>
	 */
	public function search(array $filters = [], int $limit = 10, int $offset = 0, ?array $sort = null): array
		{
		// Start with a neutral predicate so optional filters can be appended.
		$sql = "SELECT * FROM people WHERE 1=1";
		$params = [];

		// Exact ID lookup.
		if (isset($filters['id']) && $filters['id'] !== '')
			{
			$sql .= " AND id = :id";
			$params['id'] = (int) $filters['id'];
			}

		// Partial name lookup.
		if (isset($filters['name']) && $filters['name'] !== '')
			{
			$sql .= " AND `name` LIKE :name";
			$params['name'] = '%' . $filters['name'] . '%';
			}

		// Exact person type lookup.
		if (isset($filters['type']) && $filters['type'] !== '')
			{
			$sql .= " AND `type` = :type";
			$params['type'] = $filters['type'];
			}

		// Document search uses only digits to match stored normalized values.
		if (isset($filters['document']) && $filters['document'] !== '')
			{
			$sql .= " AND document LIKE :document";
			$params['document'] = onlyDigits($filters['document']);
			}

		// Active accepts only boolean-like integer values.
		if (isset($filters['active']) && $filters['active'] !== '')
			{
			$active = (int) $filters['active'];
			if (in_array($active, [0, 1], true))
				{
				$sql .= " AND active = :active";
				$params['active'] = $active;
				}
			}

		// Convert the UI date format before comparing with the database value.
		if (isset($filters['birthdate']) && $filters['birthdate'] !== '')
			{
			$sql .= " AND birthdate = :birthdate";
			$params['birthdate'] = dateBrToUs($filters['birthdate']);
			}

		$orderBy = sortOrderBy($sort, self::sortableColumns(), 'id', 'desc');
		$sql .= " ORDER BY {$orderBy} LIMIT :limit OFFSET :offset";

		$stmt = $this->db->prepare($sql);

		// Bind dynamic filters using integer bindings when possible.
		foreach ($params as $key => $value)
			{
			$paramType = is_int($value) ? PDO::PARAM_INT : PDO::PARAM_STR;
			$stmt->bindValue(':' . $key, $value, $paramType);
			}

		$stmt->bindValue(':limit', $limit, PDO::PARAM_INT);
		$stmt->bindValue(':offset', $offset, PDO::PARAM_INT);

		$stmt->execute();

		return $stmt->fetchAll(PDO::FETCH_ASSOC);
		}

	/**
	 * Counts people matching the provided filters.
	 *
	 * Uses the same main filters as `search()` so pagination totals match the
	 * visible list.
	 *
	 * @param array<string, mixed> $filters Count filters.
	 * @return int
	 */
	public function count(array $filters = []): int
		{
		// Start with a neutral predicate so optional filters can be appended.
		$sql = "SELECT COUNT(*) AS total FROM people WHERE 1=1";
		$params = [];

		// Keep count filters aligned with the search filters above.
		if (!empty($filters['id']))
			{
			$sql .= " AND id = :id";
			$params['id'] = (int) $filters['id'];
			}

		if (!empty($filters['name']))
			{
			$sql .= " AND name LIKE :name";
			$params['name'] = '%' . $filters['name'] . '%';
			}

		if (!empty($filters['type']))
			{
			$sql .= " AND `type` = :type";
			$params['type'] = $filters['type'];
			}

		if (!empty($filters['document']))
			{
			$sql .= " AND document LIKE :document";
			$params['document'] = onlyDigits($filters['document']);
			}

		if (!empty($filters['birthdate']))
			{
			$sql .= " AND birthdate = :birthdate";
			$params['birthdate'] = dateBrToUs($filters['birthdate']);
			}

		if (isset($filters['active']) && $filters['active'] !== '')
			{
			$active = (int) $filters['active'];
			if (in_array($active, [0, 1], true))
				{
				$sql .= " AND active = :active";
				$params['active'] = $active;
				}
			}

		$stmt = $this->db->prepare($sql);

		// Bind dynamic filters using integer bindings when possible.
		foreach ($params as $key => $value)
			{
			$paramType = is_int($value) ? PDO::PARAM_INT : PDO::PARAM_STR;
			$stmt->bindValue(':' . $key, $value, $paramType);
			}

		$stmt->execute();

		return (int) $stmt->fetchColumn();
		}

	/**
	 * Finds the person and all data used by the edit screen.
	 *
	 * Returns main record, user, phones, emails, addresses with neighborhood/city/state
	 * and tenants linked to the user.
	 *
	 * @param int|string $id Person ID.
	 * @return array<string, mixed>
	 */
	public function findAllByPersonId($id)
		{
		// Base person record.
		$personStmt = $this->db->prepare("SELECT * FROM people WHERE id = :id");
		$personStmt->execute(['id' => $id]);
		$person = $personStmt->fetch(PDO::FETCH_ASSOC);

		// Linked user without exposing the password hash.
		$userStmt = $this->db->prepare("SELECT id, person_id, tenant_id, username, type, active, created, modified FROM users WHERE person_id = :id");
		$userStmt->execute(['id' => $id]);
		$user = $userStmt->fetch(PDO::FETCH_ASSOC);

		// Contact phone numbers.
		$phonesStmt = $this->db->prepare("SELECT * FROM phone_numbers WHERE person_id = :id ORDER BY id ASC");
		$phonesStmt->execute(['id' => $id]);
		$phones = $phonesStmt->fetchAll(PDO::FETCH_ASSOC);

		// Contact emails.
		$emailsStmt = $this->db->prepare("SELECT * FROM emails WHERE person_id = :id ORDER BY id ASC");
		$emailsStmt->execute(['id' => $id]);
		$emails = $emailsStmt->fetchAll(PDO::FETCH_ASSOC);

		// Addresses enriched with neighborhood, city and state names.
		$addressesStmt = $this->db->prepare("SELECT Address.id,
		                                            Address.zip_code,
		                                            Address.street,
		                                            Address.number,
		                                            Address.observations,
		                                            Address.neighborhood_id,
		                                            Neighborhood.name AS neighborhood_name,
		                                            City.name AS city_name,
		                                            State.name AS state_name
		                                     FROM addresses AS Address
		                                     LEFT JOIN neighborhoods AS Neighborhood ON Neighborhood.id = Address.neighborhood_id
		                                     LEFT JOIN cities AS City ON City.id = Neighborhood.city_id
		                                     LEFT JOIN states AS State ON State.id = City.state_id
		                                     WHERE Address.person_id = :id
		                                     ORDER BY Address.id ASC");
		$addressesStmt->execute(['id' => $id]);
		$addresses = $addressesStmt->fetchAll(PDO::FETCH_ASSOC);

		// Tenant links are available only when the person has a user record.
		$tenants = [];
		if (!empty($user['id']))
			{
			$tenantsStmt = $this->db->prepare("SELECT Tenant.id,
			                                          (SELECT PersonAssoc.id
			                                             FROM tenant_users AS TenantUserAssoc
			                                             INNER JOIN users AS UserAssoc ON UserAssoc.id = TenantUserAssoc.user_id
			                                             INNER JOIN people AS PersonAssoc ON PersonAssoc.id = UserAssoc.person_id
			                                             WHERE TenantUserAssoc.tenant_id = Tenant.id
			                                             ORDER BY TenantUserAssoc.role = 'owner' DESC,
			                                                      TenantUserAssoc.created ASC,
			                                                      TenantUserAssoc.user_id ASC
			                                             LIMIT 1) AS associated_person_id,
			                                          (SELECT PersonAssoc.name
			                                             FROM tenant_users AS TenantUserAssoc
			                                             INNER JOIN users AS UserAssoc ON UserAssoc.id = TenantUserAssoc.user_id
			                                             INNER JOIN people AS PersonAssoc ON PersonAssoc.id = UserAssoc.person_id
			                                             WHERE TenantUserAssoc.tenant_id = Tenant.id
			                                             ORDER BY TenantUserAssoc.role = 'owner' DESC,
			                                                      TenantUserAssoc.created ASC,
			                                                      TenantUserAssoc.user_id ASC
			                                             LIMIT 1) AS associated_person_name,
			                                          (SELECT PersonAssoc.fantasy
			                                             FROM tenant_users AS TenantUserAssoc
			                                             INNER JOIN users AS UserAssoc ON UserAssoc.id = TenantUserAssoc.user_id
			                                             INNER JOIN people AS PersonAssoc ON PersonAssoc.id = UserAssoc.person_id
			                                             WHERE TenantUserAssoc.tenant_id = Tenant.id
			                                             ORDER BY TenantUserAssoc.role = 'owner' DESC,
			                                                      TenantUserAssoc.created ASC,
			                                                      TenantUserAssoc.user_id ASC
			                                             LIMIT 1) AS associated_person_fantasy,
			                                          (SELECT PersonAssoc.document
			                                             FROM tenant_users AS TenantUserAssoc
			                                             INNER JOIN users AS UserAssoc ON UserAssoc.id = TenantUserAssoc.user_id
			                                             INNER JOIN people AS PersonAssoc ON PersonAssoc.id = UserAssoc.person_id
			                                             WHERE TenantUserAssoc.tenant_id = Tenant.id
			                                             ORDER BY TenantUserAssoc.role = 'owner' DESC,
			                                                      TenantUserAssoc.created ASC,
			                                                      TenantUserAssoc.user_id ASC
			                                             LIMIT 1) AS associated_person_document,
			                                          Tenant.database_number,
			                                          Tenant.status,
			                                          Tenant.observations,
			                                          TenantUser.role,
			                                          TenantUser.created
			                                   FROM tenant_users AS TenantUser
			                                   INNER JOIN tenants AS Tenant ON Tenant.id = TenantUser.tenant_id
			                                   WHERE TenantUser.user_id = :user_id
			                                   ORDER BY associated_person_name ASC, Tenant.id ASC");
			$tenantsStmt->execute(['user_id' => $user['id']]);
			$tenants = $tenantsStmt->fetchAll(PDO::FETCH_ASSOC);
			}

		return [
			'person'    => $person,
			'user'      => $user,
			'phones'    => $phones,
			'emails'    => $emails,
			'addresses' => $addresses,
			'tenants'   => $tenants,
		];
		}

