	/**
	 * Searches people by name for autocomplete.
	 *
	 * The requested limit is internally restricted to the 1 to 50 range.
	 *
	 * @param string $term Partial search term.
	 * @param int $limit Requested result limit.
	 * @return array<int, array<string, mixed>>
	 */
	public function autocomplete(string $term, int $limit = 100): array
		{
		$term = trim($term);
		if ($term === '')
			{
			return [];
			}

		$limit = max(1, min(50, (int) $limit));

		// The limit is already clamped, so it is safe to inject as an integer.
		$sql = "SELECT id, `name`
						FROM people
						WHERE `name` LIKE :t
						ORDER BY COALESCE(`name`) ASC
						LIMIT {$limit}";

		$stmt = $this->db->prepare($sql);
		$stmt->execute([':t' => '%' . $term . '%']);

		return $stmt->fetchAll(\PDO::FETCH_ASSOC);
		}

	/**
	 * Deletes a person and direct dependencies within a transaction.
	 *
	 * Before deleting the person, removes permissions and tenant links from the
	 * related users, then users, addresses, emails and phone numbers.
	 *
	 * @param int|string $id Person ID.
	 * @return void
	 * @throws \Exception If any deletion fails; the transaction is rolled back.
	 */
	public function delete($id): void
		{
		try
			{
			$this->db->beginTransaction();

			// Load users first so their pivot/dependency rows can be removed.
			$stmt = $this->db->prepare("SELECT id FROM users WHERE person_id = :id");
			$stmt->execute(['id' => $id]);
			$users = $stmt->fetchAll(PDO::FETCH_ASSOC);

			// Remove dependencies owned by each user before deleting the users.
			foreach ($users as $user)
				{
				$userId = $user['id'];

				// User permissions do not have dependent rows.
				$stmt = $this->db->prepare("DELETE FROM user_permissions WHERE user_id = :user_id");
				$stmt->execute(['user_id' => $userId]);

				// Tenant links reference both tenant_id and user_id.
				$stmt = $this->db->prepare("DELETE FROM tenant_users WHERE user_id = :user_id");
				$stmt->execute(['user_id' => $userId]);
				}

			// Delete users after their dependency rows have been removed.
			$stmt = $this->db->prepare("DELETE FROM users WHERE person_id = :id");
			$stmt->execute(['id' => $id]);

			// Delete child rows that directly reference the person.
			$stmt = $this->db->prepare("DELETE FROM addresses WHERE person_id = :id");
			$stmt->execute(['id' => $id]);

			$stmt = $this->db->prepare("DELETE FROM emails WHERE person_id = :id");
			$stmt->execute(['id' => $id]);

			$stmt = $this->db->prepare("DELETE FROM phone_numbers WHERE person_id = :id");
			$stmt->execute(['id' => $id]);

			// Delete the person record last.
			$stmt = $this->db->prepare("DELETE FROM people WHERE id = :id");
			$stmt->execute(['id' => $id]);

			$this->db->commit();
			}
		catch (\Exception $e)
			{
			$this->db->rollBack();
			throw $e;
			}
		}
